def build(df):
    """df: валидация (id, prompt, response, label). Возвращает список (sid, prompt, response, label, тип)."""
    out, problems = [], []
    for pre, old, new, kind, novel in EDITS:
        rows = df[df["id"].astype(str).str.startswith(pre)]
        if len(rows) != 1:
            problems.append(f"{pre}: найдено строк {len(rows)}")
            continue
        r = rows.iloc[0]
        if int(r["label"]) != 0 or r["response"].count(old) != 1:
            problems.append(f"{pre}: исходный фрагмент не найден или метка не 0")
            continue
        if novel and novel in r["prompt"]:
            problems.append(f"{pre}: «{novel}» уже есть в контексте")
        out.append((f"SYN:{r['id']}", r["prompt"], r["response"].replace(old, new), 1, kind))
    return out, problems
